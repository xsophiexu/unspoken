// Generated from the design canvas palettes, then shaded (same hue, new lightness) wherever text
// missed WCAG AA. test/contrast.test.ts keeps every text pair at 4.5:1 or better; when you edit a
// value, run the tests and darken or lighten the same hue until they pass.
//
// Dark is "Ink and stone" (approved 2026-10-16): a near-black neutral base (saturation 2%), a deep,
// muted accent with a near-white onAccent, and a light pastel accentText. Its values come from
// dark-palettes-ink-and-stone.json on the design canvas, except where they missed AA here:
// onAccentMuted is lighter for every color, and the strongest Ombre band is darker for teal, sage
// and mustard. The dark accent tones (accentVivid, accentTint, accentShade and the deep roles) are
// the canvas formulas, hsl(accent hue, S, L), worked out for each color. accentPanel is accent in
// dark and, in light, the accent darkened until text reads on the panel's translucent tiles.

// Customize lists the colors in this order.
export const COLOR_IDS = ['teal', 'clay', 'lilac', 'sage', 'mustard', 'slateBlue', 'rose'] as const;
export type ColorId = (typeof COLOR_IDS)[number];

// Palettes an edition uses in place of the player's color (editionLooks in editions.ts). They are
// never offered on Customize.
export const EDITION_PALETTE_IDS = ['md'] as const;
export type EditionPaletteId = (typeof EDITION_PALETTE_IDS)[number];

// Every palette: the colors players pick from, then the edition palettes.
export const PALETTE_IDS = [...COLOR_IDS, ...EDITION_PALETTE_IDS] as const;
export type PaletteId = (typeof PALETTE_IDS)[number];

export const COLOR_MODES = ['light', 'dark'] as const;
export type ColorMode = (typeof COLOR_MODES)[number];

export type ColorRoles = {
  /** Full-page settings screens (Customize, Send feedback, Thanks). */
  canvas: string;
  /** The game screen and bottom sheets. */
  bg: string;
  /** Tiles, menu rows, unselected options, the Card word tile. */
  surface: string;
  /** Chips on a surface, inputs, the Deck card. */
  surfaceRaised: string;
  /** Primary text and icons. */
  ink: string;
  /** Secondary text: sublines, hints, section labels. */
  muted: string;
  /** Primary buttons, selected options, the level badge, timer progress. */
  accent: string;
  /** Text and icons on accent. */
  onAccent: string;
  /** Headline text and icons on an accent page (Sheet's header and word): pure white in dark, where onAccent is a tinted near-white. */
  onAccentStrong: string;
  /** Secondary text on accent. */
  onAccentMuted: string;
  /** Accent-colored text on bg and surfaces: Correct →, links, the Worth pill. */
  accentText: string;
  /** A brighter accent for big numerals and their progress line (Big timer's clock in dark). Same as accentText in light. */
  accentVivid: string;
  /** Accent-tinted chips on the page (Chips' banned words in dark). Same as surface in light, which is already tinted. */
  accentTint: string;
  /** A darker, quieter accent fill (Chips' Skip bar in dark). Same as surface in light. */
  accentShade: string;
  /** The accent-colored lower panel (Bottom). Accent in dark; in light a shade darker, so text still reads on its translucent tiles. */
  accentPanel: string;
  /** Borders of secondary buttons and dashed suggestion tiles. */
  outline: string;
  /** Hairlines between rows. */
  rule: string;
  /** The unfilled part of timer rings and bars. */
  track: string;
  /** Recessed fills: Split's lower half and Skip bar in dark (the track color). Same as surface in light. */
  sunken: string;
  /** The Skip bar at rest. */
  barIdle: string;
  /** The Skip bar while the card is dragged left. */
  barSkip: string;
  /** The contrasting panel: Ink and Bottom lower panels, split-bar Correct, the Ombre footer (light). */
  panel: string;
  /** Text and icons on panel. */
  onPanel: string;
  /** Secondary text on panel. */
  onPanelMuted: string;
  /** A deep accent-colored panel: the Ombre footer in dark, where panel is a neutral grey. Same as panel in light. */
  deep: string;
  /** Text and icons on deep. */
  onDeep: string;
  /** Secondary text on deep. */
  onDeepMuted: string;
  /** Borders of secondary buttons on deep (the Ombre Skip). */
  deepOutline: string;
  /** The primary button on deep (the Ombre Correct): a pale accent tint in dark. */
  deepAccent: string;
  /** Text and icons on deepAccent: a dark accent tone in dark. */
  onDeepAccent: string;
  /** Backdrop behind sheets (8-digit hex with alpha). */
  scrim: string;
  /** Ombre bands from lightest to strongest, each with its text color. */
  ramp: readonly RampBand[];
};

export type ColorRole = Exclude<keyof ColorRoles, 'ramp'>;

export type RampBand = { bg: string; ink: string };

export type Palette = {
  /** The dot on Customize. Accent can be a shade darker so white text on it passes AA. */
  swatch: string;
  light: ColorRoles;
  dark: ColorRoles;
};

